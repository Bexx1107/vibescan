'use strict';
/**
 * VibeScan persistent report store (Phase 1).
 *
 * Zero external dependencies — a plain JSON store on disk:
 *
 *   data/history.json      → ordered array of lightweight scan summaries
 *   data/reports/<id>.json → the full report for one scan
 *
 * Survives restarts (replaces the old in-memory `history` array). Kept
 * deliberately simple (JSON, not SQLite) so it stays dependency-free; the
 * read path loads only the summaries, never the full reports.
 */

const fs = require('fs');
const path = require('path');

const DATA_DIR = path.join(__dirname, '..', 'data');
const REPORTS_DIR = path.join(DATA_DIR, 'reports');
const HISTORY_FILE = path.join(DATA_DIR, 'history.json');

const MAX_HISTORY = 500; // summaries retained (reports stay until pruned)

function ensureDirs() {
  fs.mkdirSync(REPORTS_DIR, { recursive: true });
}

function readHistory() {
  try {
    const raw = fs.readFileSync(HISTORY_FILE, 'utf8');
    const parsed = JSON.parse(raw);
    return Array.isArray(parsed) ? parsed : [];
  } catch {
    return [];
  }
}

function writeHistory(list) {
  ensureDirs();
  const tmp = HISTORY_FILE + '.tmp';
  fs.writeFileSync(tmp, JSON.stringify(list, null, 2), 'utf8');
  fs.renameSync(tmp, HISTORY_FILE); // atomic replace
}

/** A short, stable key for a target URL (host + path). */
function targetKey(url) {
  try {
    const u = new URL(url);
    return (u.host + u.pathname).replace(/\/+$/, '') || u.host;
  } catch {
    return String(url || '').trim();
  }
}

function newId(startedAt) {
  const stamp = String(startedAt || new Date().toISOString()).replace(/[:.]/g, '-');
  return stamp + '-' + Math.random().toString(36).slice(2, 7);
}

const EPHEMERAL_CACHE = new Map();
const EPHEMERAL_TTL_MS = 10 * 60 * 1000;

function pruneCache() {
  const now = Date.now();
  for (const [k, v] of EPHEMERAL_CACHE.entries()) {
    if (now - v.at > EPHEMERAL_TTL_MS) EPHEMERAL_CACHE.delete(k);
  }
}

/**
 * Ephemeral in-memory report registration (ZERO disk persistence for deep low-level scans).
 * Public leaderboard stores only 1-100 summary numbers in SQLite; low-level
 * findings, headers, and DOM evidence are never written to disk.
 */
function saveReport(report) {
  pruneCache();
  const id = newId(report.startedAt);
  const meta = {
    id,
    target: report.target,
    targetKey: targetKey(report.finalUrl || report.target),
    finalUrl: report.finalUrl,
    score: report.score,
    grade: report.grade,
    durationMs: report.durationMs,
    at: report.startedAt,
    savedAt: new Date().toISOString(),
  };
  EPHEMERAL_CACHE.set(id, { report, meta, at: Date.now() });
  return meta;
}

// Defence in depth: ids are generated by newId() (<stamp>-<rand>).
const SAFE_ID = /^[A-Za-z0-9][A-Za-z0-9._-]{0,119}$/;

function getReport(id) {
  if (typeof id !== 'string' || !SAFE_ID.test(id) || id.includes('..')) return null;
  pruneCache();
  const hit = EPHEMERAL_CACHE.get(id);
  return hit ? hit.report : null;
}

/** List ephemeral summaries, newest first. */
function listHistory({ target = null, limit = 50 } = {}) {
  pruneCache();
  let list = [...EPHEMERAL_CACHE.values()].map((v) => v.meta).reverse();
  if (target) {
    const key = targetKey(target);
    list = list.filter((h) => h.targetKey === key || h.target === target || h.finalUrl === target);
  }
  return list.slice(0, Math.max(0, limit));
}

/** The two most recent reports for a target: [previous, latest]. */
function lastTwoFor(target) {
  const list = listHistory({ target, limit: 2 });
  if (list.length === 0) return { previous: null, latest: null };
  const latest = getReport(list[0].id);
  const previous = list[1] ? getReport(list[1].id) : null;
  return { previous, latest };
}

function latestFor(target) {
  const list = listHistory({ target, limit: 1 });
  return list[0] ? getReport(list[0].id) : null;
}

module.exports = {
  DATA_DIR,
  REPORTS_DIR,
  HISTORY_FILE,
  targetKey,
  saveReport,
  getReport,
  listHistory,
  lastTwoFor,
  latestFor,
};
